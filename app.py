@app.route("/create-invoice", methods=["POST"])
def create_invoice():

    try:

        # Get data from website
        data = request.get_json()

        customer_name = data.get("customerName", "")
        customer_email = data.get("customerEmail", "")
        product_name = data.get("productName", "")
        quantity = int(data.get("quantity", 1))
        price = float(data.get("price", 0))
        discount = float(data.get("discount", 0))


        # ===============================
        # CALCULATE INVOICE
        # ===============================

        subtotal = quantity * price

        total = max(
            subtotal - discount,
            0
        )


        # ===============================
        # GEMINI AI PROMPT
        # ===============================

        prompt = f"""
You are an AI Invoice Assistant.

Create a short, professional invoice summary.

Customer:
{customer_name}

Customer Email:
{customer_email}

Product / Service:
{product_name}

Quantity:
{quantity}

Price per Item:
PKR {price:,.0f}

Subtotal:
PKR {subtotal:,.0f}

Discount:
PKR {discount:,.0f}

Total:
PKR {total:,.0f}

Write a professional 2-3 sentence summary for the invoice.
Do not invent any information.
"""


        # ===============================
        # SEND TO GEMINI
        # ===============================

        response = client.models.generate_content(
            model="gemini-3.6-flash",
            contents=prompt
        )


        ai_summary = response.text
        
        # ===============================
        # GENERATE PDF
        # ===============================

        invoice_number = "INV-" + str(__import__("time").time()).replace(".", "")[-8:]

        pdf_file = create_invoice_pdf(
            invoice_number,
            customer_name,
            customer_email,
            product_name,
            quantity,
            price,
            subtotal,
            discount,
            total,
            ai_summary
        )

        # ===============================
        # RETURN RESULT
        # ===============================

        return jsonify({

            "success": True,

            "message": "Invoice created successfully with Gemini AI! 🤖",

            "invoice": {

                "customerName": customer_name,
                "customerEmail": customer_email,
                "productName": product_name,
                "quantity": quantity,
                "price": price,
                "subtotal": subtotal,
                "discount": discount,
                                "total": total,

                "aiSummary": ai_summary,

                "invoiceNumber": invoice_number,
                "pdfFile": pdf_file
            }

        })


    except Exception as error:

        print("ERROR:", error)

        return jsonify({

            "success": False,

            "message": "Something went wrong while creating the invoice.",

            "error": str(error)

        }), 500



