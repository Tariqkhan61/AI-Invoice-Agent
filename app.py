# CREATE PDF INVOICE
# ===============================

def create_invoice_pdf(
    invoice_number,
    customer_name,
    customer_email,
    product_name,
    quantity,
    price,
    subtotal,
    discount,
    total,
    ai_summary
):

    filename = f"{invoice_number}.pdf"

    pdf = canvas.Canvas(filename, pagesize=A4)

    width, height = A4

    # ===============================
    # HEADER
    # ===============================

    pdf.setFont("Helvetica-Bold", 22)
    pdf.drawString(50, height - 60, "AI INVOICE AGENT")

    pdf.setFont("Helvetica", 11)
    pdf.drawString(
        50,
        height - 80,
        "Muhammad Tariq Mahboob"
    )

    # ===============================
    # INVOICE INFORMATION
    # ===============================

    pdf.setFont("Helvetica-Bold", 11)
    pdf.drawString(
        400,
        height - 60,
        f"Invoice: {invoice_number}"
    )

    pdf.setFont("Helvetica", 10)
    pdf.drawString(
        400,
        height - 78,
        f"Date: {__import__('datetime').date.today()}"
    )

    # ===============================
    # BILL TO
    # ===============================

    y = height - 140

    pdf.setFont("Helvetica-Bold", 12)
    pdf.drawString(50, y, "BILL TO")

    pdf.setFont("Helvetica", 11)
    pdf.drawString(50, y - 20, customer_name)
    pdf.drawString(50, y - 38, customer_email)

    # ===============================
    # ITEM
    # ===============================

    y = y - 90

    pdf.setFont("Helvetica-Bold", 11)
    pdf.drawString(50, y, "DESCRIPTION")
    pdf.drawString(300, y, "QTY")
    pdf.drawString(360, y, "PRICE")
    pdf.drawString(460, y, "TOTAL")

    pdf.setFont("Helvetica", 10)

    pdf.drawString(50, y - 25, product_name)
    pdf.drawString(300, y - 25, str(quantity))
    pdf.drawString(360, y - 25, f"PKR {price:,.0f}")
    pdf.drawString(460, y - 25, f"PKR {subtotal:,.0f}")

    # ===============================
    # TOTALS
    # ===============================

    y = y - 90

    pdf.setFont("Helvetica", 11)
    pdf.drawString(
        350,
        y,
        f"Subtotal: PKR {subtotal:,.0f}"
    )

    pdf.drawString(
        350,
        y - 22,
        f"Discount: PKR {discount:,.0f}"
    )

    pdf.setFont("Helvetica-Bold", 14)
    pdf.drawString(
        350,
        y - 52,
        f"TOTAL: PKR {total:,.0f}"
    )

    # ===============================
    # AI SUMMARY
    # ===============================

    y = y - 110

    pdf.setFont("Helvetica-Bold", 12)
    pdf.drawString(
        50,
        y,
        "AI Invoice Summary"
    )

    pdf.setFont("Helvetica", 10)

    # Keep summary inside the PDF width
    words = ai_summary.split()
    line = ""
    line_y = y - 22

    for word in words:

        test_line = line + word + " "

        if pdf.stringWidth(test_line, "Helvetica", 10) < 480:

            line = test_line

        else:

            pdf.drawString(
                50,
                line_y,
                line
            )

            line = word + " "
            line_y -= 16

    if line:
        pdf.drawString(
            50,
            line_y,
            line
        )

    # ===============================
    # FOOTER
    # ===============================

    pdf.setFont("Helvetica", 9)

    pdf.drawString(
        50,
        40,
        "Generated by AI Invoice Agent"
    )

    pdf.drawString(
        50,
        25,
        "Muhammad Tariq Mahboob • Powered by Python + Gemini AI"
    )

    pdf.save()

    return filename


